"""Tests for animation-aware decode (CLAUDE.md §13.7/§13.8).

Coverage:
  - Static images pass through `load_image_frames` as a single-frame list.
  - Animated GIF / animated WebP / APNG return all frames (or up to max_frames).
  - Format allowlist: HEIF/AVIF + unidentified formats return None.
  - `is_animated_bytes` discriminates animated from static.
  - `collapse_stash_cover` returns original bytes for static, picks the
    middle frame (or per-pixel median) for animated, and returns valid
    JPEG bytes that re-decode.
  - `uniform_sample_frames` returns up to max_frames JPEG frames at
    uniform temporal indices for animated input, single frame for static.

Tests do not need DB or HTTP — pure compute over PIL-generated bytes.
"""
from __future__ import annotations

import io

import numpy as np
import pytest
from PIL import Image

from bridge.app.matching.imgmatch import frames as F


# --- Helpers to synthesize fixtures ----------------------------------------


def _solid_frame(color: tuple[int, int, int], size: int = 64) -> Image.Image:
    arr = np.zeros((size, size, 3), dtype=np.uint8)
    arr[:, :] = color
    return Image.fromarray(arr, mode="RGB")


def _gradient_frame(seed: int, size: int = 64) -> Image.Image:
    rng = np.random.default_rng(seed)
    base = np.tile(
        np.linspace(20 + (seed * 7) % 50, 200 + (seed * 11) % 50, size, dtype=np.uint8),
        (size, 1),
    )
    noise = rng.integers(0, 30, size=(size, size), dtype=np.uint8)
    arr = np.clip(base.astype(np.int32) + noise.astype(np.int32), 0, 255).astype(np.uint8)
    arr_rgb = np.stack([arr, arr, arr], axis=-1)
    return Image.fromarray(arr_rgb, mode="RGB")


def _animated_gif_bytes(n_frames: int = 5) -> bytes:
    frames = [_gradient_frame(i) for i in range(n_frames)]
    buf = io.BytesIO()
    frames[0].save(
        buf, format="GIF", save_all=True, append_images=frames[1:],
        duration=100, loop=0,
    )
    return buf.getvalue()


def _animated_webp_bytes(n_frames: int = 4) -> bytes:
    frames = [_gradient_frame(i + 100) for i in range(n_frames)]
    buf = io.BytesIO()
    frames[0].save(
        buf, format="WEBP", save_all=True, append_images=frames[1:],
        duration=100, loop=0,
    )
    return buf.getvalue()


def _apng_bytes(n_frames: int = 3) -> bytes:
    frames = [_gradient_frame(i + 200) for i in range(n_frames)]
    buf = io.BytesIO()
    frames[0].save(
        buf, format="PNG", save_all=True, append_images=frames[1:],
        duration=100, loop=0,
    )
    return buf.getvalue()


def _static_jpeg_bytes() -> bytes:
    buf = io.BytesIO()
    _gradient_frame(42).save(buf, format="JPEG", quality=92)
    return buf.getvalue()


def _static_png_bytes() -> bytes:
    buf = io.BytesIO()
    _gradient_frame(43).save(buf, format="PNG")
    return buf.getvalue()


# --- Allowlist + detection -------------------------------------------------


class TestFormatAllowlist:
    def test_supported_formats(self):
        assert "GIF" in F.SUPPORTED_FORMATS
        assert "WEBP" in F.SUPPORTED_FORMATS
        assert "PNG" in F.SUPPORTED_FORMATS
        assert "JPEG" in F.SUPPORTED_FORMATS
        # HEIF / AVIF are explicitly excluded per CLAUDE.md §13.7
        assert "HEIF" not in F.SUPPORTED_FORMATS
        assert "AVIF" not in F.SUPPORTED_FORMATS

    def test_garbage_bytes_return_none(self):
        # PIL UnidentifiedImageError → load_image_frames returns None
        assert F.load_image_frames(b"not an image at all") is None
        assert F.load_image_frames(b"") is None

    def test_heif_magic_returns_none_when_pil_cannot_decode(self):
        # Synthesized HEIF-ish header. With no plugin loaded, PIL can't
        # decode it → load_image_frames returns None (skip ref).
        # `ftypheic` is the canonical major-brand for HEIC.
        fake_heif = b"\x00\x00\x00\x18ftypheic\x00\x00\x00\x00mif1heicheix"
        assert F.load_image_frames(fake_heif) is None


# --- load_image_frames -----------------------------------------------------


class TestLoadImageFrames:
    def test_static_jpeg_returns_one_frame(self):
        frames = F.load_image_frames(_static_jpeg_bytes())
        assert frames is not None
        assert len(frames) == 1
        assert frames[0].mode == "RGB"

    def test_static_png_returns_one_frame(self):
        frames = F.load_image_frames(_static_png_bytes())
        assert frames is not None
        assert len(frames) == 1

    def test_animated_gif_returns_all_frames(self):
        frames = F.load_image_frames(_animated_gif_bytes(n_frames=5))
        assert frames is not None
        assert len(frames) == 5
        assert all(f.mode == "RGB" for f in frames)

    def test_animated_webp_returns_all_frames(self):
        frames = F.load_image_frames(_animated_webp_bytes(n_frames=4))
        assert frames is not None
        assert len(frames) == 4

    def test_apng_returns_all_frames(self):
        frames = F.load_image_frames(_apng_bytes(n_frames=3))
        assert frames is not None
        assert len(frames) == 3

    def test_max_frames_caps_animated_output(self):
        # 8 frames in, max_frames=3 caps to 3.
        frames = F.load_image_frames(_animated_gif_bytes(n_frames=8), max_frames=3)
        assert frames is not None
        assert len(frames) == 3

    def test_max_frames_zero_returns_all(self):
        frames = F.load_image_frames(_animated_gif_bytes(n_frames=8), max_frames=0)
        assert frames is not None
        assert len(frames) == 8


