# --- collapse_stash_cover --------------------------------------------------


class TestCollapseStashCover:
    def test_static_passes_through_unchanged(self):
        original = _static_jpeg_bytes()
        out = F.collapse_stash_cover(original)
        assert out is original

    def test_animated_returns_jpeg_bytes(self):
        out = F.collapse_stash_cover(_animated_gif_bytes(n_frames=5))
        assert out is not None
        # Re-decode the result to confirm it's a valid still image.
        img = Image.open(io.BytesIO(out))
        assert img.format == "JPEG"
        assert not getattr(img, "is_animated", False)

    def test_middle_mode_picks_middle_frame(self):
        # Animated GIF where each frame is a distinct gradient seed —
        # the middle frame should be visually closer to seed=2 (out of 0..4)
        # than to seed=0 or 4.
        gif = _animated_gif_bytes(n_frames=5)
        out = F.collapse_stash_cover(gif, mode="middle")
        assert out is not None
        # Sanity: the result decodes and isn't empty.
        img = Image.open(io.BytesIO(out)).convert("RGB")
        arr = np.asarray(img)
        assert arr.size > 0
        assert arr.var() > 0  # non-uniform

    def test_median_mode_returns_synthetic_frame(self):
        out = F.collapse_stash_cover(_animated_gif_bytes(n_frames=5), mode="median")
        assert out is not None
        img = Image.open(io.BytesIO(out)).convert("RGB")
        # Per-pixel median across distinct gradient frames yields a valid
        # synthetic image with non-zero variance.
        assert np.asarray(img).var() > 0

    def test_unsupported_format_returns_none(self):
        assert F.collapse_stash_cover(b"garbage bytes") is None


# --- uniform_sample_frames -------------------------------------------------


class TestUniformSampleFrames:
    def test_animated_gif_returns_jpeg_frames(self):
        out = F.uniform_sample_frames(
            _animated_gif_bytes(n_frames=8),
            max_frames=8,
        )
        assert out is not None
        assert len(out) == 8
        for frame in out:
            img = Image.open(io.BytesIO(frame))
            assert img.format == "JPEG"

    def test_max_frames_caps_output(self):
        # 12 frames available, ask for 4 → exactly 4 returned.
        out = F.uniform_sample_frames(
            _animated_gif_bytes(n_frames=12),
            max_frames=4,
        )
        assert out is not None
        assert len(out) == 4

    def test_max_frames_above_n_total_returns_all(self):
        # 4 frames available, ask for 8 → exactly 4 returned (no padding).
        out = F.uniform_sample_frames(
            _animated_gif_bytes(n_frames=4),
            max_frames=8,
        )
        assert out is not None
        assert len(out) == 4

    def test_uniform_indices_span_temporal_extent(self):
        # 100 frames, ask for 5 → first frame ≈ index 0, last ≈ index 99.
        # We can't directly check indices from JPEG bytes, but per-frame
        # color shifts let us verify diversity (animated_gif_bytes generates
        # frames with rng-seeded color differences). The 5 frames should
        # not all be identical pixel-for-pixel.
        out = F.uniform_sample_frames(
            _animated_gif_bytes(n_frames=100),
            max_frames=5,
        )
        assert out is not None
        assert len(out) == 5
        # Distinct decoded frames — not all the same JPEG.
        assert len(set(out)) >= 2

    def test_static_input_returns_single_frame(self):
        # Static JPEG → single-element list (encoded as JPEG).
        from bridge.app.matching.imgmatch import frames as F2
        # Make a static PNG
        rng = np.random.default_rng(0)
        arr = rng.integers(0, 255, size=(32, 32, 3), dtype=np.uint8)
        buf = io.BytesIO()
        Image.fromarray(arr, mode="RGB").save(buf, format="PNG")
        out = F.uniform_sample_frames(buf.getvalue(), max_frames=8)
        assert out is not None
        assert len(out) == 1

    def test_garbage_bytes_returns_none(self):
        out = F.uniform_sample_frames(
            b"not a valid animation", max_frames=4,
        )
        assert out is None

    def test_unsupported_format_returns_none(self):
        # HEIF mock — set format to something outside the allowlist
        # by pretending. Easier: garbage already covers this; cover the
        # decode-failure-after-open path explicitly.
        out = F.uniform_sample_frames(b"", max_frames=4)
        assert out is None
